# Variables and list setup
fam = ["liz", 1.73, "emma", 1.68, "mom", 1.71, "dad", 1.89]

# List Methods

# gets the index number of mom
print(fam.index("mom"))

# gets the count of 1.71
print(fam.count(1.71))


# Str Methods

# Create string variable
sister = "liz"

# Capitalize the first letter
print(sister.capitalize())

# Replace "z" with "zy"
print(sister.replace("z", "zy"))
